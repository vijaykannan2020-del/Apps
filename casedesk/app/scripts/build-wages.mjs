// Builds the app's offline prevailing-wage data from DOL's yearly "OFLC Wages" zip (same files FLAG uses).
// Usage: node scripts/build-wages.mjs <unzipped OFLC folder> <wage year, e.g. 2026-27>
// Output: assets/wages/index.json (states + occupations) and assets/wages/<STATE>.wage (counties → wage area → levels).
import fs from 'node:fs';
import path from 'node:path';
import readline from 'node:readline';

const [dir, wageYear] = process.argv.slice(2);
if (!dir || !wageYear) { console.error('usage: build-wages.mjs <dir> <wageYear>'); process.exit(1); }
const OUT = path.resolve('assets/wages');

function parseLine(line, sep) {
  const out = []; let cur = '', q = false;
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (q) { if (c === '"') { if (line[i + 1] === '"') { cur += '"'; i++; } else q = false; } else cur += c; }
    else if (c === '"') q = true; else if (c === sep) { out.push(cur); cur = ''; } else cur += c;
  }
  out.push(cur); return out.map((s) => s.trim());
}
async function* rows(file) {
  const b = Buffer.alloc(2); const fd = fs.openSync(file, 'r'); fs.readSync(fd, b, 0, 2, 0); fs.closeSync(fd);
  const enc = b[0] === 0xff && b[1] === 0xfe ? 'utf16le' : 'utf8';
  const rl = readline.createInterface({ input: fs.createReadStream(file, { encoding: enc }), crlfDelay: Infinity });
  let head = null, sep = ',';
  for await (let line of rl) {
    line = line.replace(/^﻿/, ''); if (!line.trim()) continue;
    if (!head) { sep = line.split('\t').length > line.split(',').length ? '\t' : ','; head = parseLine(line, sep).map((h) => h.toLowerCase().replace(/[^a-z0-9]/g, '')); continue; }
    const c = parseLine(line, sep); const r = {}; head.forEach((h, i) => (r[h] = c[i] ?? '')); yield r;
  }
}
const find = (re) => { const f = fs.readdirSync(dir).find((n) => re.test(n)); if (!f) throw new Error(`missing ${re}`); return path.join(dir, f); };

// Occupations
const soc = [];
for await (const r of rows(find(/^oes_soc_occs.*\.csv$/i))) if (r.soccode) soc.push([r.soccode, r.title]);
soc.sort((a, b) => a[0].localeCompare(b[0]));
const socIdx = new Map(soc.map((s, i) => [s[0], i]));

// Wages per area: "socIdx,l1,l2,l3,l4" with hourly wages in cents
const byArea = new Map();
let n = 0;
for await (const r of rows(find(/^alc_export.*\.csv$/i))) {
  const area = r.area, i = socIdx.get(r.soccode);
  const lv = [r.level1, r.level2, r.level3, r.level4].map((x) => Math.round(parseFloat(x) * 100));
  if (!area || i === undefined || !lv.every((x) => x > 0)) continue;
  if (!byArea.has(area)) byArea.set(area, []);
  byArea.get(area).push([i, ...lv].join(','));
  n++;
}

// Counties/towns → wage area, by state (same mapping FLAG uses)
const states = {}; const areaName = {};
for await (const r of rows(find(/^geography.*\.csv$/i))) {
  const st = r.stateab, county = r.countytownname, area = r.area;
  if (!st || !county || !area) continue;
  areaName[area] = r.areaname;
  states[st] ||= { name: r.state || st, counties: [] };
  if (!states[st].counties.some((c) => c[0] === county)) states[st].counties.push([county, area]);
}

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });
let total = 0;
for (const [st, s] of Object.entries(states)) {
  const areas = {};
  for (const [, a] of s.counties) if (!areas[a] && byArea.has(a)) areas[a] = [areaName[a], byArea.get(a).join(';')];
  const body = JSON.stringify({ state: st, counties: s.counties.sort((a, b) => a[0].localeCompare(b[0])), areas });
  fs.writeFileSync(path.join(OUT, `${st}.wage`), body);
  total += body.length;
}
fs.writeFileSync(path.join(OUT, 'index.json'), JSON.stringify({ wageYear, states: Object.entries(states).map(([code, s]) => [code, s.name]).sort((a, b) => a[1].localeCompare(b[1])), soc }));
// Static require map for Metro (assets must be required by literal path)
const codes = Object.keys(states).sort();
fs.writeFileSync(path.resolve('src/data/wageFiles.ts'), `// Generated by scripts/build-wages.mjs — do not edit.\nexport const WAGE_FILES: Record<string, number> = {\n${codes.map((c) => `  ${JSON.stringify(c)}: require('../../assets/wages/${c}.wage'),`).join('\n')}\n};\n`);
console.log(`Wage year ${wageYear}: ${n.toLocaleString()} wage rows, ${soc.length} occupations, ${codes.length} states, ${(total / 1e6).toFixed(1)} MB of state files.`);
